from __future__ import annotations

import asyncio
import math
import os

import httpx
from apify import Actor

API = os.environ.get("TRANSCRIPTYT_BASE_URL", "https://transcript-yt.com")
BATCH = 50
PARALLEL_BATCHES = 4
TRANSCRIPT_EVENT = "transcript"
AI_MINUTE_EVENT = "ai-transcription-minute"


class ApiError(Exception):
    pass


async def call(client: httpx.AsyncClient, method: str, path: str, **kwargs) -> dict:
    for attempt in range(4):
        response = await client.request(method, API + path, **kwargs)
        if response.status_code in (429, 502, 503, 504) and attempt < 3:
            await asyncio.sleep(2**attempt * 2)
            continue
        body = response.json()
        if response.is_error:
            error = body.get("error")
            raise ApiError(error.get("message") if isinstance(error, dict) else str(error))
        return body
    raise AssertionError("unreachable")


async def collect_videos(client: httpx.AsyncClient, actor_input: dict) -> list[str]:
    videos = [v.strip() for v in actor_input.get("videos") or [] if v and v.strip()]
    limit = actor_input.get("maxVideos") or 50
    if source := (actor_input.get("playlistOrChannel") or "").strip():
        listed = await call(client, "GET", "/v1/playlist", params={"url": source, "limit": limit})
        Actor.log.info(f"Playlist/channel: {len(listed['videos'])} videos")
        videos += [v["videoId"] for v in listed["videos"]]
    if query := (actor_input.get("searchQuery") or "").strip():
        found = await call(client, "GET", "/v1/search", params={"q": query, "limit": min(limit, 100)})
        Actor.log.info(f"Search '{query}': {len(found['videos'])} videos")
        videos += [v["videoId"] for v in found["videos"]]
    return list(dict.fromkeys(videos))


def item_for(result: dict, fmt: str) -> dict:
    if not result["ok"]:
        error = result.get("error") or {}
        return {"url": result["url"], "error": f"{error.get('code')}: {error.get('message')}"}
    if "transcript" not in result:
        return {"url": result["url"], "format": fmt, "content": result.get("body")}
    t = result["transcript"]
    return {
        "url": f"https://www.youtube.com/watch?v={t['videoId']}",
        "videoId": t["videoId"],
        "title": t.get("title"),
        "author": t.get("author"),
        "channelId": t.get("channelId"),
        "durationSeconds": t.get("durationSeconds"),
        "language": t.get("language"),
        "translated": t.get("translated"),
        "autoGenerated": t.get("autoGenerated"),
        "source": t.get("source"),
        "text": t.get("text"),
        "segments": t.get("segments") or None,
        "availableLanguages": t.get("availableLanguages"),
    }


async def main() -> None:
    async with Actor:
        actor_input = await Actor.get_input() or {}
        api_key = os.environ.get("TRANSCRIPTYT_API_KEY")
        if not api_key:
            raise RuntimeError("TRANSCRIPTYT_API_KEY is not set on the Actor.")
        fmt = actor_input.get("format") or "json"
        options = {
            "format": fmt,
            "includeSegments": actor_input.get("includeSegments", True),
            "timestamps": actor_input.get("timestamps", False),
            "mode": "auto" if actor_input.get("aiFallback") else "captions",
            **{k: actor_input[k] for k in ("language",) if actor_input.get(k)},
            **({"translate_to": actor_input["translateTo"]} if actor_input.get("translateTo") else {}),
        }

        headers = {"Authorization": f"Bearer {api_key}", "User-Agent": "transcriptyt-apify/0.1"}
        async with httpx.AsyncClient(headers=headers, timeout=600) as client:
            try:
                videos = await collect_videos(client, actor_input)
            except ApiError as e:
                await Actor.fail(status_message=str(e))
                return
            if not videos:
                await Actor.fail(status_message="Add at least one video URL, a playlist/channel URL, or a search query.")
                return
            Actor.log.info(f"Fetching transcripts for {len(videos)} videos")

            stop = asyncio.Event()
            done = {"ok": 0, "failed": 0}
            semaphore = asyncio.Semaphore(PARALLEL_BATCHES)

            async def run_batch(urls: list[str]) -> None:
                async with semaphore:
                    if stop.is_set():
                        return
                    try:
                        batch = await call(client, "POST", "/v1/transcripts", json={"urls": urls, **options})
                    except ApiError as e:
                        Actor.log.error(f"Batch failed: {e}")
                        await Actor.push_data([{"url": u, "error": str(e)} for u in urls])
                        done["failed"] += len(urls)
                        return
                    for result in batch["results"]:
                        if stop.is_set():
                            return
                        item = item_for(result, fmt)
                        if not result["ok"]:
                            await Actor.push_data(item)
                            done["failed"] += 1
                            continue
                        charge = await Actor.push_data(item, charged_event_name=TRANSCRIPT_EVENT)
                        done["ok"] += 1
                        if item.get("source") == "speech_to_text":
                            minutes = max(1, math.ceil((item.get("durationSeconds") or 0) / 60))
                            charge = await Actor.charge(AI_MINUTE_EVENT, count=minutes)
                        if charge and charge.event_charge_limit_reached:
                            Actor.log.info("Reached the run's maximum charge; stopping.")
                            stop.set()
                            return
                    await Actor.set_status_message(f"{done['ok']} transcripts, {done['failed']} failed")

            await asyncio.gather(*(run_batch(videos[i : i + BATCH]) for i in range(0, len(videos), BATCH)))
            await Actor.set_status_message(f"Done: {done['ok']} transcripts, {done['failed']} failed", is_terminal=True)
